def db_exec(query, params=()):
    with wms.db_connect() as conn:
        with conn.cursor() as cur:
            cur.execute(query, params)
        conn.commit()


def db_one(query, params=()):
    return wms.query_one(query, params)[0]


def _hold_pg_advisory_lock(ready, release, status):
    """Independent Python process holds real PostgreSQL advisory lock."""
    import wb_fbs_sync_v11 as mod
    try:
        with mod._exclusive_sync(ACCOUNT):
            status.put("LOCKED")
            ready.set()
            if not release.wait(15):
                raise TimeoutError("test lock holder timed out")
    except BaseException as exc:
        status.put("ERROR:" + repr(exc))
        ready.set()


class PGStress(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        # Creating only minimal tables used by real atomic commit_scan().
        # This database is generated by the isolated runner, never an app DB.
        commands = [
            """CREATE TABLE employees (id TEXT PRIMARY KEY, name TEXT NOT NULL)""",
            """CREATE TABLE shifts (id TEXT PRIMARY KEY,employee_id TEXT NOT NULL,started_at TEXT NOT NULL,ended_at TEXT)""",
            """CREATE TABLE activities (id TEXT PRIMARY KEY,shift_id TEXT NOT NULL,employee_id TEXT NOT NULL,activity_type TEXT NOT NULL,started_at TEXT NOT NULL,ended_at TEXT)""",
            """CREATE TABLE fbs_pending_products (shift_id TEXT PRIMARY KEY, employee_id TEXT NOT NULL, product_barcode TEXT NOT NULL, article TEXT,product_name TEXT,started_at TEXT NOT NULL)""",
            """CREATE TABLE scans (id TEXT PRIMARY KEY,shift_id TEXT NOT NULL,employee_id TEXT NOT NULL,barcode TEXT UNIQUE NOT NULL,product_barcode TEXT,article TEXT,product_name TEXT,wb_order_id TEXT,scan_type TEXT,scanned_at TEXT,marketplace TEXT)""",
            """CREATE TABLE fbs_scan_requests (request_id TEXT PRIMARY KEY,scan_id TEXT NOT NULL,shift_id TEXT NOT NULL,employee_id TEXT NOT NULL,barcode TEXT NOT NULL,product_barcode TEXT NOT NULL)""",
            """CREATE TABLE operation_events (id TEXT PRIMARY KEY,employee_id TEXT NOT NULL,shift_id TEXT,operation_type TEXT,event_type TEXT,object_code TEXT,quantity REAL,result TEXT,article TEXT,product_name TEXT,created_at TEXT NOT NULL)""",
        ]
        with wms.db_connect() as conn:
            with conn.cursor() as cur:
                for stmt in commands:
                    cur.execute(stmt)
            conn.commit()
        wb.init_schema()
        # Bulk seed 10,000 fully synthetic orders and their exact SKU/sticker.
        db_exec("""INSERT INTO wb_fbs_orders
            (account_id,order_id,nm_id,chrt_id,seller_article,wb_status,local_status,synced_at)
            SELECT %s, (900000000+g)::text, '1000', '2000','SYNTHETIC',
                   'confirm','pending',%s FROM generate_series(1,%s) g""",
                (ACCOUNT, STAMP, N_ORDERS))
        db_exec("""INSERT INTO wb_fbs_order_skus(account_id,order_id,sku)
            SELECT %s,(900000000+g)::text,'SYNTH-SKU-'||g::text
            FROM generate_series(1,%s) g""", (ACCOUNT, N_ORDERS))
        db_exec("""INSERT INTO wb_fbs_stickers(account_id,order_id,barcode,fetched_at)
            SELECT %s,(900000000+g)::text,'SYNTH-WB-'||g::text,%s
            FROM generate_series(1,%s) g""", (ACCOUNT, STAMP, N_ORDERS))
        for i in range(N_TERMINALS):
            employee, shift = f"synthetic-employee-{i}", f"synthetic-shift-{i}"
            db_exec("INSERT INTO employees VALUES(%s,%s)", (employee, employee))
            db_exec("INSERT INTO shifts VALUES(%s,%s,%s,NULL)", (shift, employee, STAMP))
            db_exec("INSERT INTO activities VALUES(%s,%s,%s,'picking',%s,NULL)",
                    (f"synthetic-activity-{i}", shift, employee, STAMP))
        assert db_one("SELECT COUNT(*) FROM wb_fbs_orders") == N_ORDERS

    @staticmethod
    def pending(i, n):
        db_exec("""INSERT INTO fbs_pending_products
            (shift_id,employee_id,product_barcode,article,product_name,started_at)
            VALUES(%s,%s,%s,'SYNTHETIC','SYNTHETIC',%s)
            ON CONFLICT(shift_id) DO UPDATE
            SET product_barcode=EXCLUDED.product_barcode,
                article=EXCLUDED.article,product_name=EXCLUDED.product_name,
                started_at=EXCLUDED.started_at""",
            (f"synthetic-shift-{i}",f"synthetic-employee-{i}",
             f"SYNTH-SKU-{n}",STAMP))

    @staticmethod
    def scan(i, n):
        start = time.perf_counter()
        commit_scan(f"synthetic-shift-{i}", f"synthetic-employee-{i}",
                    f"SYNTH-WB-{n}", f"SYNTH-SKU-{n}", "SYNTHETIC", "SYNTHETIC",
                    None, "normal", str(uuid.uuid4()), True)
        return (time.perf_counter()-start)*1000

    def test_01_ten_concurrent_terminals_commit_1000_orders(self):
        def worker(i):
            latencies = []
            for x in range(N_SCANS_PER_TERMINAL):
                n = i * N_SCANS_PER_TERMINAL + x + 1
                self.pending(i,n)
                latencies.append(self.scan(i,n))
            return latencies
        start = time.perf_counter()
        with concurrent.futures.ThreadPoolExecutor(max_workers=N_TERMINALS) as exe:
            all_batches = list(exe.map(worker,range(N_TERMINALS)))
        delays = sorted(ms for batch in all_batches for ms in batch)
        elapsed = time.perf_counter()-start
        p95 = delays[int(len(delays)*0.95)-1]
        print(f"STRESS: synthetic_orders={N_ORDERS} terminals={N_TERMINALS} "
              f"commits={len(delays)} elapsed_s={elapsed:.2f} "
              f"avg_ms={statistics.mean(delays):.1f} p95_ms={p95:.1f}",
              flush=True)
        self.assertEqual(len(delays), N_TERMINALS*N_SCANS_PER_TERMINAL)
        self.assertEqual(db_one("SELECT COUNT(*) FROM scans"),len(delays))
        self.assertEqual(db_one("SELECT COUNT(*) FROM wb_fbs_orders WHERE local_status='complete'"), len(delays))
        self.assertEqual(db_one("SELECT COUNT(*) FROM scans WHERE barcode <> 'SYNTH-WB-' || (wb_order_id::bigint - 900000000)::text"),0)
        self.assertEqual(db_one("""SELECT COUNT(*) FROM scans s
            LEFT JOIN wb_fbs_orders o ON o.order_id=s.wb_order_id AND o.account_id=%s
            WHERE o.order_id IS NULL OR o.local_status<>'complete'""",(ACCOUNT,)),0)

    def test_02_double_commit_is_rejected_across_workers(self):
        # A second active worker with the SAME WB sticker/order must never
        # add a second scan, even after scanning the exact matching product.
        self.pending(1,1)
        with self.assertRaises(Exception):
            self.scan(1,1)
        self.assertEqual(db_one("SELECT COUNT(*) FROM scans WHERE barcode='SYNTH-WB-1'"),1)

    def test_02b_simultaneous_duplicate_order_one_winner(self):
        # Different shifts racing the same fresh sticker must create ONE scan.
        from threading import Barrier
        number=1600
        for i in (0,1):
            self.pending(i,number)
        barrier=Barrier(2)
        def race(i):
            barrier.wait(timeout=5)
            try:
                self.scan(i,number)
                return "OK"
            except Exception:
                return "REJECTED"
        with concurrent.futures.ThreadPoolExecutor(max_workers=2) as pool:
            outcome=list(pool.map(race,(0,1)))
        self.assertEqual(sorted(outcome),["OK","REJECTED"])
        self.assertEqual(db_one("SELECT COUNT(*) FROM scans WHERE barcode=%s",
                                (f"SYNTH-WB-{number}",)),1)
        self.assertEqual(db_one("SELECT COUNT(*) FROM wb_fbs_orders WHERE order_id=%s AND local_status='complete'",
                                (str(ORDER_BASE+number),)),1)

    def test_03_wrong_sku_does_not_increment(self):
        self.pending(0,1500)
        before=db_one("SELECT COUNT(*) FROM scans")
        with self.assertRaises(ValueError):
            commit_scan("synthetic-shift-0", "synthetic-employee-0",
                        "SYNTH-WB-1500", "SYNTH-SKU-1499",
                        "SYNTHETIC","SYNTHETIC",None,"normal",str(uuid.uuid4()),True)
        self.assertEqual(db_one("SELECT COUNT(*) FROM scans"),before)

    def test_04_cancelled_order_is_blocked_after_prior_match(self):
        self.pending(0,1501)
        self.assertEqual(wb.verify_pair(ACCOUNT,"SYNTH-SKU-1501","SYNTH-WB-1501")["result"],"MATCH")
        db_exec("""UPDATE wb_fbs_orders SET wb_status='cancel'
            WHERE account_id=%s AND order_id=%s""",(ACCOUNT,str(ORDER_BASE+1501)))
        with self.assertRaises(ValueError):
            self.scan(0,1501)
        self.assertEqual(db_one("SELECT COUNT(*) FROM scans WHERE barcode='SYNTH-WB-1501'"),0)

    def test_05_cross_process_pg_lock_does_not_overlap(self):
        ctx=mp.get_context("spawn")
        ready, release, status = ctx.Event(),ctx.Event(),ctx.Queue()
        holder=ctx.Process(target=_hold_pg_advisory_lock,args=(ready,release,status))
        holder.start()
        try:
            self.assertTrue(ready.wait(12),"holder did not start")
            self.assertEqual(status.get(timeout=5),"LOCKED")
            with self.assertRaises(RuntimeError):
                with wb._exclusive_sync(ACCOUNT):
                    self.fail("Two processes held the same account lock")
        finally:
            release.set()
            holder.join(timeout=10)
            if holder.is_alive():
                holder.terminate()
                holder.join(5)
        self.assertEqual(holder.exitcode,0)
        with wb._exclusive_sync(ACCOUNT):
            pass  # Lock must be released after holder finishes.

