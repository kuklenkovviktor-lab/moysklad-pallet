#!/usr/bin/env bash
# Only removes resources named in the explicit PR192 demo state file.
set -Eeuo pipefail
STATE="${GRIT_PR192_DEMO_STATE:-/tmp/grit-pr192-demo.state}"
# Deliberately support only two known disposable demo state files.
# Never follow symlinks, and never infer container names from production state.
case "$STATE" in
  /tmp/grit-pr192-demo.state|/tmp/grit-pr204-demo.state|/tmp/grit-pr205-demo.state|/tmp/grit-pr206-demo.state) ;;
  *) echo "Refusing unexpected synthetic demo state path" >&2; exit 2;;
esac
if test -L "$STATE"; then
  echo "Refusing symlink demo state path" >&2
  exit 2
fi
if [ ! -f "$STATE" ]; then
  echo "No PR192 demo state found; nothing to stop."
  exit 0
fi
# Only owner-readable state generated by run_line_printer_demo.sh.
source "$STATE"
[[ "$NET" == grit-pr192demo-* && "$DB" == grit-db-pr192demo-* && "$APP" == grit-ui-pr192demo-* ]] || {
  echo "Refusing unexpected container/network IDs"; exit 3;
}
docker rm -f "$APP" "$DB" >/dev/null 2>&1 || true
docker network rm "$NET" >/dev/null 2>&1 || true
rm -f "$STATE"
echo "PR192 ISOLATED DEMO STOPPED. Production unchanged."
